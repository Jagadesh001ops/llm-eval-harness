"""Fill the generated results block of README.md from the result files (no hand-typed numbers in the tables).

Replaces everything between <!-- RESULTS:START --> and <!-- RESULTS:END --> with:
  * the per-task test-gain tables from results/opt/summary.md
  * a transfer table from results/opt/transfer.csv
  * a hypotheses scorecard from results/opt/hypotheses.csv

    python analysis/make_readme_tables.py
"""

import pathlib
import re

import numpy as np
import pandas as pd

ROOT = pathlib.Path("results/opt")
README = pathlib.Path("README.md")
FAMILY = {"gemma3-4b": "gemma", "gemma3-12b": "gemma", "gemma3-27b": "gemma",
          "ministral-3b": "ministral", "ministral-8b": "ministral", "ministral-14b": "ministral"}
CONDS = ["strong-closed", "strong-open", "mid", "larger", "self", "control"]
TITLES = {"ag_news": "AG News (accuracy, 500 test items)", "squad_v2": "SQuAD 2.0 (F1, 500 test items)",
          "triviaqa": "TriviaQA closed-book, the control (exact match, 500 test items)"}


def task_tables():
    md = (ROOT / "summary.md").read_text(encoding="utf-8")
    out = []
    for task, title in TITLES.items():
        m = re.search(rf"^## {task} .*?\n(.*?)(?=^## )", md, re.S | re.M)
        body = m.group(1).strip()
        out += [f"#### {title}", "", body, ""]
    return "\n".join(out)


def transfer_table():
    T = pd.read_csv(ROOT / "transfer.csv")
    T["cross"] = [FAMILY[a] != FAMILY[b] for a, b in zip(T.source_target, T.dest_target)]
    rows = ["| Task | Optimizer | Pairs | Mean gain on other targets | Share of pairs that gain | Cross-family mean gain |",
            "|---|---|---|---|---|---|"]
    for task in ["ag_news", "squad_v2", "triviaqa"]:
        for c in CONDS:
            g = T[(T.task == task) & (T.condition == c)]
            if g.empty:
                continue
            cross = g[g.cross].gain.mean()
            rows.append(f"| {task} | {c} | {len(g)} | {g.gain.mean()*100:+.1f} | {(g.gain > 0).mean():.0%} | "
                        f"{'n/a' if np.isnan(cross) else f'{cross*100:+.1f}'} |")
    return "\n".join(rows)


def scorecard():
    H = pd.read_csv(ROOT / "hypotheses.csv")
    desc = {
        "H1": "Strong (Opus) test gain > self, per target",
        "H3": "Self beats the no-feedback control",
        "H5": "Larger same-family optimizer is non-inferior to Opus (lower CI bound > -1 pt)",
        "H8": "Mistral Large 3 within +/-2 points of Opus (equivalence)",
    }
    rows = ["| Hypothesis | Cells tested | Supported | Inconclusive / not supported | Contradicted |", "|---|---|---|---|---|"]
    for h, text in desc.items():
        g = H[H.hypothesis == h]
        sup = int((g.verdict == "supported").sum())
        con = int((g.verdict == "contradicted").sum())
        rows.append(f"| {h}: {text} | {len(g)} | {sup} | {len(g) - sup - con} | {con} |")
    return "\n".join(rows)


def main():
    block = "\n".join([
        "<!-- RESULTS:START (generated by analysis/make_readme_tables.py; do not edit by hand) -->", "",
        "Gains are test-set points over the starting prompt (final prompt minus seed prompt on identical items), mean over "
        "runs, with 95% intervals from a two-level bootstrap (runs, then items). 3 runs per cell for Gemma on AG News and "
        "SQuAD, 2 for Ministral, 1 for TriviaQA. `-` = condition not defined (no larger model exists). The last column is "
        "the hand-written oracle prompt's absolute score, for reference.", "",
        task_tables(), "#### Prompt transfer (final prompts scored unchanged on the other targets of the same task)", "",
        transfer_table(), "", "#### Hypotheses scorecard", "", scorecard(), "",
        "Full per-cell numbers, process measures, the without-judge sensitivity and the length analysis: "
        "`results/opt/summary.md`, `results/opt/hypotheses.csv`, `results/opt/transfer.csv`.", "",
        "<!-- RESULTS:END -->"])
    text = README.read_text(encoding="utf-8")
    new, n = re.subn(r"<!-- RESULTS:START.*?<!-- RESULTS:END -->", lambda _: block, text, flags=re.S)
    assert n == 1, "markers not found in README.md"
    README.write_text(new, encoding="utf-8")
    print("README results block regenerated")


if __name__ == "__main__":
    main()
