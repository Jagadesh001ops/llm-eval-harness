"""Validate the intent judge against blind human labels (design doc §6.3).

Inputs:  results/judge_validation/items.json        blind items (id, prompt)
         results/judge_validation/human_labels.json  {item_id: {"label": keep|change|unsure, "note": ...}}
         results/judge_validation/key.json           item sources (pilot vs constructed)
Outputs: results/judge_validation/judge_verdicts.json   one verdict per item (cached; reruns skip done items)
         results/judge_validation/report.md, report.json

Acceptance (pre-registered): agreement >= 0.85 AND Cohen's kappa >= 0.70 on items the human labelled keep/change.
Items the human marked 'unsure' are excluded from agreement and listed separately.

    python scripts/validate_judge.py
"""

import json
import pathlib
import sys

import numpy as np

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
from harness.intent import load_task_card  # noqa: E402
from harness.judge import JUDGE_MODEL, IntentJudge  # noqa: E402
from harness.stats import DEFAULT_SEED  # noqa: E402

D = pathlib.Path("results/judge_validation")
AGREE_MIN, KAPPA_MIN = 0.85, 0.70
TO_JUDGE = {"keep": "keeps", "change": "changes"}


def cohen_kappa(a, b):
    a, b = np.asarray(a), np.asarray(b)
    po = (a == b).mean()
    cats = sorted(set(a) | set(b))
    pe = sum((a == c).mean() * (b == c).mean() for c in cats)
    return float("nan") if pe == 1 else (po - pe) / (1 - pe)


def bootstrap_kappa(a, b, B=10_000, seed=DEFAULT_SEED):
    a, b = np.asarray(a), np.asarray(b)
    idx = np.random.default_rng(seed).integers(0, len(a), size=(B, len(a)))
    ks = np.array([cohen_kappa(a[i], b[i]) for i in idx])
    ks = ks[~np.isnan(ks)]
    return tuple(np.quantile(ks, [0.025, 0.975]))


def main():
    card = load_task_card("ag_news")
    seed = pathlib.Path("prompts/v2/ag_news.txt").read_text(encoding="utf-8")
    items = json.loads((D / "items.json").read_text(encoding="utf-8"))
    human = json.loads((D / "human_labels.json").read_text(encoding="utf-8"))
    key = json.loads((D / "key.json").read_text(encoding="utf-8"))

    vpath = D / "judge_verdicts.json"
    verdicts = json.loads(vpath.read_text(encoding="utf-8")) if vpath.exists() else {}
    judge = None
    for it in items:
        if it["id"] in verdicts and verdicts[it["id"]]["verdict"] != "error":
            continue
        judge = judge or IntentJudge()
        verdicts[it["id"]] = judge.judge(card, seed, it["prompt"])
        vpath.write_text(json.dumps(verdicts, indent=1), encoding="utf-8")
        print(it["id"], verdicts[it["id"]]["verdict"])

    rows = []
    for it in items:
        h = human.get(it["id"], {}).get("label")
        rows.append({"id": it["id"], "human": h, "judge": verdicts[it["id"]]["verdict"],
                     "source": key[it["id"]]["source"], "kind": key[it["id"]].get("kind"),
                     "condition": key[it["id"]].get("condition"), "human_note": human.get(it["id"], {}).get("note"),
                     "judge_reason": verdicts[it["id"]]["reason"], "prompt": it["prompt"]})
    decided = [r for r in rows if r["human"] in TO_JUDGE and r["judge"] in ("keeps", "changes")]
    h = [TO_JUDGE[r["human"]] for r in decided]
    j = [r["judge"] for r in decided]
    agree = float(np.mean([x == y for x, y in zip(h, j)])) if decided else float("nan")
    kappa = cohen_kappa(h, j) if decided else float("nan")
    k_lo, k_hi = bootstrap_kappa(h, j) if len(decided) > 5 else (float("nan"), float("nan"))
    passed = agree >= AGREE_MIN and kappa >= KAPPA_MIN

    cons = [r for r in rows if r["source"] == "constructed"]
    summary = {
        "judge_model": JUDGE_MODEL, "n_items": len(rows), "n_decided": len(decided),
        "n_human_unsure": sum(r["human"] == "unsure" for r in rows),
        "n_human_missing": sum(r["human"] is None for r in rows),
        "n_judge_error": sum(r["judge"] == "error" for r in rows),
        "agreement": agree, "kappa": kappa, "kappa_ci95": [k_lo, k_hi],
        "thresholds": {"agreement": AGREE_MIN, "kappa": KAPPA_MIN}, "passed": passed,
        "constructed_caught_by_human": sum(r["human"] == "change" for r in cons),
        "constructed_caught_by_judge": sum(r["judge"] == "changes" for r in cons),
        "n_constructed": len(cons),
        "pilot_flagged_by_human": sum(r["human"] == "change" for r in rows if r["source"] == "pilot"),
        "pilot_flagged_by_judge": sum(r["judge"] == "changes" for r in rows if r["source"] == "pilot"),
        "judge_cost_usd": sum(v["cost_usd"] for v in verdicts.values()),
    }
    (D / "report.json").write_text(json.dumps({"summary": summary, "rows": rows}, indent=1), encoding="utf-8")

    md = [f"# Intent judge validation ({JUDGE_MODEL})", "",
          f"Generated by `python scripts/validate_judge.py`. Pre-registered bar: agreement >= {AGREE_MIN:.0%} and "
          f"Cohen's kappa >= {KAPPA_MIN} on items the human labelled keep/change.", "",
          f"- Items: {len(rows)} ({len(rows) - len(cons)} pilot rewrites, {len(cons)} constructed intent-changing)",
          f"- Decided by both: {len(decided)}; human unsure: {summary['n_human_unsure']}; "
          f"human missing: {summary['n_human_missing']}; judge errors: {summary['n_judge_error']}",
          f"- **Agreement: {agree:.1%}**, **kappa: {kappa:.2f}** (95% CI {k_lo:.2f} to {k_hi:.2f})",
          f"- **Result: {'PASSED' if passed else 'FAILED'}**",
          f"- Constructed items flagged as changing intent: human {summary['constructed_caught_by_human']}/{len(cons)}, "
          f"judge {summary['constructed_caught_by_judge']}/{len(cons)}",
          f"- Pilot rewrites flagged as changing intent: human {summary['pilot_flagged_by_human']}, "
          f"judge {summary['pilot_flagged_by_judge']}",
          f"- Judge cost: ${summary['judge_cost_usd']:.3f}", "", "## Disagreements and unsure items", ""]
    for r in rows:
        if r["human"] == "unsure" or (r["human"] in TO_JUDGE and TO_JUDGE[r["human"]] != r["judge"]):
            md += [f"### {r['id']} ({r['source']}{', ' + r['kind'] if r['kind'] else ''}"
                   f"{', ' + r['condition'] if r['condition'] else ''})",
                   f"Human: **{r['human']}**" + (f", note: {r['human_note']}" if r["human_note"] else ""),
                   f"Judge: **{r['judge']}**, reason: {r['judge_reason']}", "", "```", r["prompt"], "```", ""]
    (D / "report.md").write_text("\n".join(md), encoding="utf-8")
    print("\n".join(md[:12]))


if __name__ == "__main__":
    main()
